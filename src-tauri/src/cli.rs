#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn launcher_has_config_dir_token_and_exec() {
        let s = render_launcher("Work", "work", "/tmp/cfg dir", "/opt/homebrew/bin/claude");
        assert!(s.contains("export CLAUDE_CONFIG_DIR=\"/tmp/cfg dir\""));
        assert!(s.contains("com.claudeprofiles.cli.work"));
        assert!(s.contains("export CLAUDE_CODE_OAUTH_TOKEN=\"$TOKEN\""));
        assert!(s.trim_end().ends_with("exec \"$CLAUDE_BIN\" \"$@\""));
    }

    #[test]
    fn sh_sq_quote_escapes_single_quotes() {
        assert_eq!(sh_sq_quote("/tmp/plain"), "'/tmp/plain'");
        assert_eq!(sh_sq_quote("/Users/O'Brien/x"), "'/Users/O'\\''Brien/x'");
    }

    #[test]
    fn launcher_escapes_quotes_in_name() {
        let s = render_launcher("Ac\"me", "acme", "/tmp/x", "/bin/claude");
        assert!(s.contains("Ac\\\"me"));
    }

    #[test]
    fn escapes_shell_metacharacters() {
        // The point of the escaper: neutralize $, backtick, ", \ inside a double-quoted bash string.
        assert_eq!(sh_dq_escape("a\"b"), "a\\\"b");
        assert_eq!(sh_dq_escape("a\\b"), "a\\\\b");
        assert_eq!(sh_dq_escape("$(whoami)"), "\\$(whoami)");
        assert_eq!(sh_dq_escape("`id`"), "\\`id\\`");
    }

    #[test]
    fn parse_prefers_sk_ant_token() {
        let raw = "Some banner\nYour token:\nsk-ant-oat01-ABCDEF123456\nDone.";
        assert_eq!(parse_setup_token_output(raw).as_deref(), Some("sk-ant-oat01-ABCDEF123456"));
    }

    #[test]
    fn parse_falls_back_to_last_line() {
        assert_eq!(parse_setup_token_output("  \n  hello-token  \n\n").as_deref(), Some("hello-token"));
    }

    #[test]
    fn parse_empty_is_none() {
        assert_eq!(parse_setup_token_output("   \n  "), None);
    }

    #[test]
    fn extract_email_works() {
        let j = r#"{"userID":"x","oauthAccount":{"emailAddress":"a@b.com","org":"y"}}"#;
        assert_eq!(extract_email(j).as_deref(), Some("a@b.com"));
        assert_eq!(extract_email(r#"{"no":"email"}"#), None);
    }
}
