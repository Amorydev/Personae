// Claude Code CLI profile engine. Parallels macos.rs (Desktop), but isolates the
// *CLI*: a per-profile CLAUDE_CONFIG_DIR plus a per-profile OAuth token injected
// via CLAUDE_CODE_OAUTH_TOKEN (which overrides the shared macOS Keychain slot).
use serde::Serialize;

#[derive(Serialize, Clone)]
pub struct CliProfile {
    pub name: String,
    pub slug: String,
    pub config_dir: String,   // CLAUDE_CONFIG_DIR for this profile
    pub launcher_path: String, // the generated .command
    pub has_token: bool,       // a token is stored in the Keychain for this slug
    pub account_email: Option<String>, // parsed from <config_dir>/.claude.json if present
    pub data_size: String,
    pub created: Option<u64>,
    pub last_active: Option<u64>,
}

pub const KEYCHAIN_PREFIX: &str = "com.claudeprofiles.cli";

/// Escape a string for safe interpolation inside a double-quoted bash string.
pub fn sh_dq_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if matches!(c, '"' | '\\' | '$' | '`') {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// Wrap a string as a safe POSIX single-quoted shell word (handles embedded ').
pub fn sh_sq_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// The bash body of a profile launcher. Reads the token from the Keychain at run
/// time (never bakes it into the file) and execs the real claude CLI.
/// Precondition: `slug` must be pre-slugified ([a-z0-9-], via platform::slugify) — it is interpolated raw into the Keychain service/account strings.
pub fn render_launcher(name: &str, slug: &str, config_dir: &str, claude_bin: &str) -> String {
    let name_e = sh_dq_escape(name);
    let cfg_e = sh_dq_escape(config_dir);
    let bin_e = sh_dq_escape(claude_bin);
    let svc = format!("{KEYCHAIN_PREFIX}.{slug}");
    format!(
        "#!/bin/bash\n\
         # Generated by Claude Profiles — CLI account launcher for \"{name_e}\".\n\
         export CLAUDE_CONFIG_DIR=\"{cfg_e}\"\n\
         TOKEN=\"$(security find-generic-password -w -s \"{svc}\" -a \"{slug}\" 2>/dev/null)\"\n\
         if [ -z \"$TOKEN\" ]; then\n\
         \x20 echo \"No saved token for profile \\\"{name_e}\\\".\"\n\
         \x20 echo \"Open Claude Profiles and use \\\"Set token\\\" for this profile.\"\n\
         \x20 exit 1\n\
         fi\n\
         export CLAUDE_CODE_OAUTH_TOKEN=\"$TOKEN\"\n\
         CLAUDE_BIN=\"{bin_e}\"\n\
         [ -x \"$CLAUDE_BIN\" ] || CLAUDE_BIN=\"$(command -v claude)\"\n\
         exec \"$CLAUDE_BIN\" \"$@\"\n"
    )
}

/// Extract a usable token from whatever the user pasted (a bare token, or the
/// full `claude setup-token` output). Prefer an sk-ant-* token; else last line.
pub fn parse_setup_token_output(raw: &str) -> Option<String> {
    for tok in raw.split_whitespace() {
        if tok.starts_with("sk-ant-") && tok.len() > 12 {
            return Some(tok.to_string());
        }
    }
    raw.lines()
        .rev()
        .map(|l| l.trim())
        .find(|l| !l.is_empty())
        .map(|s| s.to_string())
}

/// Cheap extract of oauthAccount.emailAddress from a .claude.json body without
/// pulling in serde_json.
pub fn extract_email(json: &str) -> Option<String> {
    let key = "\"emailAddress\"";
    let i = json.find(key)? + key.len();
    let rest = &json[i..];
    let start = rest.find('"')? + 1;
    let after = &rest[start..];
    let end = after.find('"')?;
    let email = &after[..end];
    if email.contains('@') { Some(email.to_string()) } else { None }
}

#[cfg(target_os = "macos")]
mod imp {
    use super::*;
    use crate::platform::{home, run};
    use std::fs;
    use std::os::unix::fs::PermissionsExt;
    use std::path::PathBuf;

    // ~/Applications/Claude Profiles CLI/<name>.command
    pub fn launcher_root() -> PathBuf { home().join("Applications/Claude Profiles CLI") }
    // ~/Library/Application Support/ClaudeProfilesCLI/<slug>   (== CLAUDE_CONFIG_DIR)
    pub fn config_root() -> PathBuf { home().join("Library/Application Support/ClaudeProfilesCLI") }

    pub fn launcher_path(name: &str) -> PathBuf { launcher_root().join(format!("{name}.command")) }
    pub fn config_dir(slug: &str) -> PathBuf { config_root().join(slug) }
    pub fn keychain_service(slug: &str) -> String { format!("{KEYCHAIN_PREFIX}.{slug}") }

    /// Resolve the claude CLI binary (env override → PATH → common install dirs).
    pub fn claude_bin() -> Option<PathBuf> {
        if let Ok(p) = std::env::var("CLAUDE_CLI_BIN") {
            let pb = PathBuf::from(p);
            if pb.is_file() { return Some(pb); }
        }
        let (ok, out) = run("which", &["claude"]);
        if ok {
            let p = PathBuf::from(out.trim());
            if p.is_file() { return Some(p); }
        }
        for c in [
            "/opt/homebrew/bin/claude", "/usr/local/bin/claude",
            "~/.local/bin/claude", "~/.claude/local/claude", "~/.bun/bin/claude",
        ] {
            let pb = if let Some(rest) = c.strip_prefix("~/") { home().join(rest) } else { PathBuf::from(c) };
            if pb.is_file() { return Some(pb); }
        }
        None
    }

    pub fn kc_set(slug: &str, token: &str) -> Result<(), String> {
        let svc = keychain_service(slug);
        // -U updates in place if the item already exists.
        let (ok, out) = run("security", &["add-generic-password", "-U", "-s", &svc, "-a", slug, "-w", token]);
        if ok { Ok(()) } else { Err(format!("Keychain write failed: {}", out.trim())) }
    }

    pub fn kc_has(slug: &str) -> bool {
        let svc = keychain_service(slug);
        run("security", &["find-generic-password", "-s", &svc, "-a", slug]).0
    }

    pub fn kc_delete(slug: &str) {
        let svc = keychain_service(slug);
        let _ = run("security", &["delete-generic-password", "-s", &svc, "-a", slug]);
    }

    pub fn write_launcher(name: &str, slug: &str) -> Result<(), String> {
        let cfg = config_dir(slug);
        let bin = claude_bin().map(|p| p.display().to_string()).unwrap_or_default();
        let body = render_launcher(name, slug, &cfg.display().to_string(), &bin);
        let lp = launcher_path(name);
        fs::create_dir_all(launcher_root()).map_err(|e| e.to_string())?;
        fs::write(&lp, body).map_err(|e| e.to_string())?;
        let mut perm = fs::metadata(&lp).map_err(|e| e.to_string())?.permissions();
        perm.set_mode(0o755);
        fs::set_permissions(&lp, perm).map_err(|e| e.to_string())
    }

}

// ---- public API (macOS) --------------------------------------------------
#[cfg(target_os = "macos")]
pub fn available() -> bool { imp::claude_bin().is_some() }

#[cfg(target_os = "macos")]
pub fn create(name: &str) -> Result<(), String> {
    use crate::platform::slugify;
    let slug = slugify(name);
    if slug.is_empty() { return Err("Name must contain letters or numbers.".into()); }
    let lp = imp::launcher_path(name);
    if lp.exists() { return Err(format!("CLI profile already exists: {}", lp.display())); }
    std::fs::create_dir_all(imp::config_dir(&slug)).map_err(|e| e.to_string())?;
    imp::write_launcher(name, &slug)?;
    Ok(())
}

#[cfg(target_os = "macos")]
pub fn set_token(name: &str, token: &str) -> Result<(), String> {
    use crate::platform::slugify;
    let slug = slugify(name);
    let clean = parse_setup_token_output(token)
        .ok_or("No token found in the pasted text.")?;
    imp::kc_set(&slug, &clean)
}

#[cfg(target_os = "macos")]
pub fn open_setup_token(name: &str) -> Result<(), String> {
    use crate::platform::slugify;
    let slug = slugify(name);
    if !imp::launcher_path(name).exists() { return Err(format!("No such CLI profile: {name}")); }
    let bin = imp::claude_bin().ok_or("Claude Code CLI not found (install `claude`).")?;
    let cfg = imp::config_dir(&slug);
    // Single-quote the shell paths; the whole command is a double-quoted AppleScript string.
    let shell_cmd = format!(
        "export CLAUDE_CONFIG_DIR={}; {} setup-token; echo; echo '↑ COPY THE TOKEN ABOVE, then paste it into Claude Profiles.'",
        sh_sq_quote(&cfg.display().to_string()), sh_sq_quote(&bin.display().to_string())
    );
    // AppleScript double-quoted string: escape backslash first, then double-quote.
    let as_arg = shell_cmd.replace('\\', "\\\\").replace('"', "\\\"");
    let script = format!("tell application \"Terminal\" to do script \"{}\"", as_arg);
    let (ok, out) = crate::platform::run("osascript", &["-e", &script, "-e", "tell application \"Terminal\" to activate"]);
    if ok { Ok(()) } else { Err(out.trim().to_string()) }
}

#[cfg(target_os = "macos")]
pub fn launch(name: &str) -> Result<(), String> {
    let lp = imp::launcher_path(name);
    if !lp.exists() { return Err(format!("No such CLI profile: {name}")); }
    let (ok, e) = crate::platform::run("open", &[&lp.display().to_string()]);
    if ok { Ok(()) } else { Err(e) }
}

#[cfg(target_os = "macos")]
pub fn has_token(name: &str) -> bool {
    imp::kc_has(&crate::platform::slugify(name))
}

#[cfg(target_os = "macos")]
pub fn list() -> Vec<CliProfile> {
    use crate::platform::{run, slugify, to_secs};
    let mut out = vec![];
    let rd = match std::fs::read_dir(imp::launcher_root()) { Ok(r) => r, Err(_) => return out };
    for e in rd.flatten() {
        let p = e.path();
        if p.extension().map_or(false, |x| x == "command") {
            let name = p.file_stem().unwrap_or_default().to_string_lossy().to_string();
            let slug = slugify(&name);
            let cfg = imp::config_dir(&slug);
            let data_size = if cfg.exists() {
                let (_, o) = run("du", &["-sh", &cfg.display().to_string()]);
                o.split('\t').next().unwrap_or("—").trim().to_string()
            } else { "—".into() };
            let account_email = std::fs::read_to_string(cfg.join(".claude.json")).ok()
                .and_then(|j| extract_email(&j));
            let md = std::fs::metadata(&cfg).ok();
            let created = md.as_ref().and_then(|m| m.created().ok()).and_then(to_secs);
            let last_active = md.as_ref().and_then(|m| m.modified().ok()).and_then(to_secs);
            out.push(CliProfile {
                name, slug: slug.clone(),
                config_dir: cfg.display().to_string(),
                launcher_path: p.display().to_string(),
                has_token: imp::kc_has(&slug),
                account_email, data_size, created, last_active,
            });
        }
    }
    out.sort_by(|a, b| a.name.to_lowercase().cmp(&b.name.to_lowercase()));
    out
}

#[cfg(target_os = "macos")]
pub fn delete(name: &str, purge: bool) -> Result<(), String> {
    use crate::platform::slugify;
    let slug = slugify(name);
    let lp = imp::launcher_path(name);
    if !lp.exists() { return Err(format!("No such CLI profile: {name}")); }
    std::fs::remove_file(&lp).map_err(|e| e.to_string())?;
    if purge {
        imp::kc_delete(&slug);
        let cfg = imp::config_dir(&slug);
        if cfg.exists() { std::fs::remove_dir_all(&cfg).map_err(|e| e.to_string())?; }
    }
    Ok(())
}

